export function getTrackKey(careerGoal: string, interests: string[] = []): string {
  const query = `${careerGoal} ${interests.join(' ')}`.toLowerCase();

  if (query.includes('front') || query.includes('ui') || query.includes('react')) {
    return 'frontend';
  }
  if (query.includes('back') || query.includes('api') || query.includes('node') || query.includes('system design')) {
    return 'backend';
  }
  if (query.includes('ai') || query.includes('machine learning') || query.includes('ml') || query.includes('deep learning')) {
    return 'aiml';
  }
  if (query.includes('data') || query.includes('analytics') || query.includes('bi')) {
    return 'datascience';
  }
  if (query.includes('devops') || query.includes('cloud') || query.includes('docker') || query.includes('kubernetes') || query.includes('sre')) {
    return 'devops';
  }
  return 'fullstack';
}
